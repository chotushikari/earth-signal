import assert from 'node:assert/strict';
import {contextFromSearch,contextParams,searchParams,screenPair,candidatePairs,makeDataset,evidenceManifest} from '../src/services/discovery/workflow.js';
const context=contextFromSearch('?bounds=76,9,76.5,9.5&start=2026-01-01&end=2026-11-01&product=GCOV');
assert.equal(context.area.wkt,'POLYGON((76 9,76.5 9,76.5 9.5,76 9.5,76 9))');
assert.deepEqual(contextFromSearch(contextParams(context)),context);
assert.equal(searchParams(context).get('intersectsWith'),context.area.wkt);
assert.equal(searchParams(context).get('start'),'2026-01-01');
assert.equal(contextFromSearch('?product=all').product,'');
assert.equal(contextFromSearch('?bounds=0,0,180,90').place.valid,false);
const a={granuleName:'NISAR_L2_UR_GCOV_035_113_A_006_4005_DHDH_A_20261113T003207_TEST',startTime:'2026-11-13T00:32:07Z',processingLevel:'GCOV',track:113,frameNumber:6,flightDirection:'ASCENDING',sensor:'L-SAR',polarization:'HH',pgeVersion:'v1',stringFootprint:'POLYGON ((76 9,77 9,77 10,76 9))'};
const b={...a,granuleName:a.granuleName.replace('20261113','20261001'),startTime:'2026-10-01T00:32:07Z'};
assert.equal(screenPair(a,b).candidate,true);
assert.equal(screenPair(a,{...b,track:null}).candidate,false);
assert.equal(screenPair(a,{...b,processingLevel:'SME2'}).candidate,false);
assert.equal(screenPair(a,{...b,frameNumber:7}).candidate,false);
assert.equal(screenPair(a,{...b,startTime:a.startTime}).candidate,false);
assert.equal(screenPair(a,{...b,stringFootprint:'POLYGON EMPTY'}).candidate,false);
assert.equal(screenPair(a,{...b,pgeVersion:null}).candidate,false);
assert.equal(candidatePairs([a,b]).length,1);
const dataset=makeDataset({records:[a,a,b],limit:80,query:{intersectsWith:context.area.wkt}},context,'test');
assert.equal(dataset.records.length,2);
const manifest=evidenceManifest(dataset,[a.granuleName,b.granuleName]);
assert.equal(manifest.science.status,'not_run');assert.equal(manifest.science.measurements,null);assert.equal(manifest.query.intersectsWith,context.area.wkt);
console.log('Workflow AOI/date/product round-trip, conservative pairing, deduplication and evidence truth gates passed.');
